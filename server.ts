// ZOD SCHEMAS FOR STRICT OUTPUT VALIDATION
// ----------------------------------------------------
const AISearchSchema = z.object({
  originalQuery: z.string().default(''),
  suggestedCategory: z.enum(['all', 'electronics', 'laptops', 'boots', 'bluetooth', 'hair-care', 'sports']).default('all'),
  maxPrice: z.number().optional(),
  minRating: z.number().optional(),
  extractedKeywords: z.array(z.string()).default([]),
  keyFeatures: z.array(z.string()).default([]),
  reasoning: z.string().default('AI evaluated matching criteria based on product attributes.'),
  matchedProductIds: z.array(z.string()).default([])
});

const AICompareSchema = z.object({
  productIds: z.array(z.string()).default([]),
  overview: z.string().default('Comparison overview generated by AI.'),
  featuresComparison: z.array(
    z.object({
      featureName: z.string(),
      values: z.record(z.string(), z.string())
    })
  ).default([]),
  prosAndCons: z.record(
    z.string(),
    z.object({
      pros: z.array(z.string()),
      cons: z.array(z.string())
    })
  ).default({}),
  bestFor: z.record(z.string(), z.string()).default({}),
  verdict: z.string().default('Selection recommendation based on specs and value.'),
  recommendedProductId: z.string().default('')
});

const AIReviewSchema = z.object({
  productId: z.string().default(''),
  sentimentScore: z.number().min(0).max(100).default(85),
  totalReviewsAnalyzed: z.number().default(0),
  keyPros: z.array(z.string()).default([]),
  keyCons: z.array(z.string()).default([]),
  summaryVerdict: z.string().default('Highly rated product according to customer feedback.')
});

// Helper function to query Claude with JSON enforcement
async function queryClaudeJSON(systemPrompt: string, userPrompt: string): Promise<any> {
  if (!anthropicClient) {
    throw new Error('Claude API client is not configured.');
  }

  const response = await anthropicClient.messages.create({
    model: 'claude-3-5-sonnet-20241022',
    max_tokens: 1024,
    temperature: 0.2,
    system: `${systemPrompt}\nIMPORTANT: Respond strictly with valid JSON. Do NOT include markdown codeblocks (\`\`\`json), commentary, or extra text before or after the JSON payload.`,
    messages: [
      {
        role: 'user',
        content: userPrompt
      }
    ]
  });

  const textBlock = response.content.find(c => c.type === 'text');
  if (!textBlock || !textBlock.text) {
    throw new Error('Empty response received from Claude API.');
  }

  const cleanedText = textBlock.text.trim().replace(/^```json\s*/i, '').replace(/\s*```$/i, '');
  return JSON.parse(cleanedText);
}

