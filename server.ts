// 1. NATURAL LANGUAGE SEARCH ENDPOINT
// ----------------------------------------------------
app.post('/api/ai/search', async (req: Request, res: Response) => {
  try {
    const { query, products } = req.body;

    if (!query || typeof query !== 'string') {
      return res.status(400).json({ error: 'Valid query parameter is required.' });
    }

    if (!anthropicClient) {
      return res.status(503).json({
        fallback: true,
        message: 'Claude API key not available on server. Using fallback heuristic search.',
        data: null
      });
    }

    const catalogSummary = (products || []).map((p: any) => ({
      id: p.id,
      name: p.name,
      category: p.category,
      price: p.price,
      rating: p.rating?.rate,
      brand: p.brand,
      description: p.description
    }));

    const systemPrompt = `You are a high-performance e-commerce AI shopping assistant. Analyze the user's natural language shopping request and match it against the provided product catalog. Output JSON matching this schema:
{
  "originalQuery": string,
  "suggestedCategory": "all" | "electronics" | "laptops" | "boots" | "bluetooth" | "hair-care" | "sports",
  "maxPrice": number or null,
  "minRating": number or null,
  "extractedKeywords": string[],
  "keyFeatures": string[],
  "reasoning": string,
  "matchedProductIds": string[]
}`;

    const userPrompt = `User Query: "${query}"\n\nProduct Catalog:\n${JSON.stringify(catalogSummary, null, 2)}`;

    const rawResult = await queryClaudeJSON(systemPrompt, userPrompt);
    const validatedData = AISearchSchema.parse({ ...rawResult, originalQuery: query });

    return res.json({ success: true, data: validatedData });
  } catch (error: any) {
    console.error('Error in /api/ai/search:', error?.message || error);
    return res.status(500).json({
      success: false,
      fallback: true,
      error: error?.message || 'Failed to process AI search request.',
      data: null
    });
  }
});

