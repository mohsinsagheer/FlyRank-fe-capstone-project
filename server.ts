// 2. PRODUCT COMPARISON ENDPOINT
// ----------------------------------------------------
app.post('/api/ai/compare', async (req: Request, res: Response) => {
  try {
    const { products } = req.body;

    if (!products || !Array.isArray(products) || products.length < 2) {
      return res.status(400).json({ error: 'At least 2 products are required for comparison.' });
    }

    if (!anthropicClient) {
      return res.status(503).json({
        fallback: true,
        message: 'Claude API key not configured. Using fallback local comparison.',
        data: null
      });
    }

    const comparisonInput = products.map((p: any) => ({
      id: p.id,
      name: p.name,
      brand: p.brand,
      price: p.price,
      originalPrice: p.originalPrice,
      rating: p.rating?.rate,
      specifications: p.specifications,
      description: p.description
    }));

    const systemPrompt = `You are an expert product reviewer and analyst. Compare the selected products objectively. Output strict JSON with key feature matrix, pros/cons for each product (by productId), target audience ("bestFor"), concise overview, and final verdict with recommendedProductId.
Format JSON:
{
  "productIds": string[],
  "overview": string,
  "featuresComparison": [
    { "featureName": string, "values": { "[productId]": string } }
  ],
  "prosAndCons": {
    "[productId]": { "pros": string[], "cons": string[] }
  },
  "bestFor": {
    "[productId]": string
  },
  "verdict": string,
  "recommendedProductId": string
}`;

    const userPrompt = `Compare these products:\n${JSON.stringify(comparisonInput, null, 2)}`;

    const rawResult = await queryClaudeJSON(systemPrompt, userPrompt);
    const validatedData = AICompareSchema.parse({
      ...rawResult,
      productIds: products.map((p: any) => p.id)
    });

    return res.json({ success: true, data: validatedData });
  } catch (error: any) {
    console.error('Error in /api/ai/compare:', error?.message || error);
    return res.status(500).json({
      success: false,
      fallback: true,
      error: error?.message || 'Failed to compare products via AI.',
      data: null
    });
  }
});

